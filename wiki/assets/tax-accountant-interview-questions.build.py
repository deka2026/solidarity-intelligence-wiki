C_STAR = doc.ensure_run_style(bold=True, size=10, color="#C0392B", font=FONT)

def pidx():
    return len(list(doc.paragraphs)) - 1

def para(text="", char=C_BODY, *, align=None, before=0, after=4, indent=0, spacing=160, keep=None):
    p = doc.add_paragraph(text, char_pr_id_ref=char, inherit_style=False, para_pr_id_ref=0, style_id_ref=0)
    kw = dict(paragraph_index=pidx(), spacing_before_pt=before, spacing_after_pt=after, line_spacing_percent=spacing)
    if align: kw["alignment"] = align
    if indent: kw["indent_left_mm"] = indent
    if keep is not None: kw["keep_with_next"] = keep
    doc.set_paragraph_format(**kw)
    return p

def h1(text):
    para(text, C_H1, before=14, after=6, keep=True)

def h2(text):
    para(text, C_H2, before=8, after=3, keep=True)

def bullet(text, char=C_BODY):
    para("• " + text, char, after=2, indent=3)

def cell_write(tbl, r, c, text, char=C_CELL, shade=None, lines=None):
    cell = tbl.cell(r, c)
    parts = lines if lines is not None else [text]
    cell.set_text(parts[0])
    for run in cell.paragraphs[0].runs:
        run.char_pr_id_ref = char
    for extra in parts[1:]:
        cell.add_paragraph(extra, char_pr_id_ref=char, para_pr_id_ref=0, style_id_ref=0)
    if shade:
        tbl.set_cell_shading(r, c, shade)

def table(rows, header, widths, shade="#DCE6F1", body_char=C_CELL, first_col_bold=False):
    t = doc.add_table(len(rows) + 1, len(header), width=BODY_W)
    t.set_column_widths(widths)
    for j, h in enumerate(header):
        cell_write(t, 0, j, h, C_CELLB, shade=shade)
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            lines = val if isinstance(val, list) else None
            ch = C_CELLB if (first_col_bold and j == 0) else body_char
            cell_write(t, i, j, val if lines is None else "", ch, lines=lines)
    para("", C_BODY, after=2)
    return t

def qtable(questions):
    """questions: list of (num, star, text or [lines])"""
    t = doc.add_table(len(questions) + 1, 4, width=BODY_W)
    t.set_column_widths([0.9, 0.7, 7.4, 4.0])
    for j, h in enumerate(["번호", "★", "질문", "답변 메모"]):
        cell_write(t, 0, j, h, C_CELLB, shade="#DCE6F1")
    for i, (num, star, text) in enumerate(questions, start=1):
        cell_write(t, i, 0, str(num), C_CELL)
        cell_write(t, i, 1, "★" if star else "", C_STAR)
        lines = text if isinstance(text, list) else None
        cell_write(t, i, 2, text if lines is None else "", C_CELL, lines=lines)
        cell_write(t, i, 3, "", C_CELL)
        if star:
            t.set_cell_shading(i, 1, "#FBEAE5")
    para("", C_BODY, after=2)

